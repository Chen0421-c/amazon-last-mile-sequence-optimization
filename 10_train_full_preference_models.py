def save_prediction_file(df: Any, y_prob: Any, model_name: str, output_path: Path) -> None:
    output_columns = [column for column in PREDICTION_ID_COLUMNS if column in df.columns]
    missing = [column for column in PREDICTION_ID_COLUMNS if column not in df.columns]
