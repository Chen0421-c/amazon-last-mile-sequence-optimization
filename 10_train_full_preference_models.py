def prepare_output_dir(output_dir: Path, overwrite: bool) -> tuple[Path, Path | None]:
    backup_dir = None
    generated_names = {
        "model_comparison_validation.csv",
        "model_comparison_test.csv",
        "model_comparison_combined.csv",
        "best_model_summary.csv",
        "best_model_summary.json",
        "feature_columns.json",
        "feature_importance.csv",
        "models_trained.csv",
        "models_skipped.csv",
        "training_run_summary.csv",
        "models",
        "predictions",
    }

    if output_dir.exists() and any(output_dir.iterdir()) and not overwrite:
        raise FileExistsError(
            f"Output directory exists and is not empty: {output_dir}. "
            "Use --overwrite to replace generated outputs."
        )

    output_dir.mkdir(parents=True, exist_ok=True)
    if overwrite:
        for name in generated_names:
            target = output_dir / name
            if target.is_dir():
                shutil.rmtree(target)
            elif target.exists():
                target.unlink()

    models_dir = output_dir / "models"
    models_dir.mkdir(parents=True, exist_ok=True)
    return models_dir, backup_dir


def train_and_evaluate(args: argparse.Namespace) -> None:
    import pandas as pd

    config = load_config(args.config)
    settings = resolve_runtime_settings(args, config)
    input_dir: Path = settings["input_dir"]
    output_dir: Path = settings["output_dir"]
    seed: int = settings["seed"]
    requested_models = requested_models_from_args(args, config)

    print(f"Input directory: {input_dir}")
    print(f"Output directory: {output_dir}")
    print(f"Seed: {seed}")
    print(f"Requested models: {requested_models}")

    needed_columns = list(dict.fromkeys([*PREDICTION_ID_COLUMNS, *DEFAULT_FEATURE_COLUMNS]))
    split_frames = {
        split: read_pairwise_split(input_dir, split, args.input_format, needed_columns)
        for split in VALID_SPLITS
    }

    for split, df in split_frames.items():
        validate_pairwise_data(df, split)

    split_frames["train"] = sample_decision_contexts(
        split_frames["train"], args.max_train_contexts, seed
    )
    if args.max_train_contexts is None:
        split_frames["train"] = sample_rows(
            split_frames["train"], args.max_train_rows, seed, "train"
        )
    split_frames["validation"] = sample_decision_contexts(
        split_frames["validation"], args.max_validation_contexts, seed
    )
    split_frames["test"] = sample_decision_contexts(
        split_frames["test"], args.max_test_contexts, seed
    )

    split_summaries = {
        split: validate_pairwise_data(df, split) for split, df in split_frames.items()
    }

    train_features = get_feature_columns(split_frames["train"])
    common_features = [
        feature
        for feature in train_features
        if all(feature in split_frames[split].columns for split in VALID_SPLITS)
    ]
    missing_default_features = [
        feature
        for feature in DEFAULT_FEATURE_COLUMNS
        if feature not in common_features
    ]
    if missing_default_features:
        warnings.warn(
            "The following default features are unavailable in all splits and "
            f"will not be used: {missing_default_features}"
        )
    if not common_features:
        raise ValueError("No usable feature columns are present in all splits.")

    print(f"Feature columns used ({len(common_features)}): {common_features}")

    models_dir, _backup_dir = prepare_output_dir(output_dir, args.overwrite)
    predictions_dir = output_dir / "predictions"
    if args.save_predictions:
        predictions_dir.mkdir(parents=True, exist_ok=True)

    X_train, y_train = prepare_xy(split_frames["train"], common_features)
    X_validation, y_validation = prepare_xy(split_frames["validation"], common_features)
    X_test, y_test = prepare_xy(split_frames["test"], common_features)

    validation_results = []
    test_results = []
    trained_models = {}
    trained_model_rows = []
    skipped_model_rows = []
    feature_importance_rows = []
    validation_predictions = {}
    test_predictions = {}

    for model_name in requested_models:
        print(f"\nTraining model: {model_name}")
        try:
            model = train_model(model_name, X_train, y_train, seed, args.class_weight)
            validation_metrics, validation_prob = evaluate_split(
                model_name, model, split_frames["validation"], X_validation, y_validation
            )
            test_metrics, test_prob = evaluate_split(
                model_name, model, split_frames["test"], X_test, y_test
            )

            model_path = models_dir / f"{model_name}.joblib"
            save_model(model, model_path)

            validation_results.append(validation_metrics)
            test_results.append(test_metrics)
            trained_models[model_name] = model
            trained_model_rows.append(
                {"model_name": model_name, "model_path": str(model_path)}
            )
            feature_importance_rows.extend(
                extract_feature_importance(model, model_name, common_features)
            )
            validation_predictions[model_name] = validation_prob
            test_predictions[model_name] = test_prob

            print(
                f"{model_name}: validation top1="
                f"{validation_metrics['sampled_top1_accuracy']}, "
                f"test top1={test_metrics['sampled_top1_accuracy']}"
            )
        except Exception as exc:
            reason = f"{type(exc).__name__}: {exc}"
            print(f"Skipping {model_name}: {reason}")
            skipped_model_rows.append({"model_name": model_name, "reason": reason})

    validation_results_df = pd.DataFrame(validation_results)
    test_results_df = pd.DataFrame(test_results)
    skipped_models_df = pd.DataFrame(skipped_model_rows, columns=MODEL_SKIPPED_COLUMNS)

    skipped_models_df.to_csv(output_dir / "models_skipped.csv", index=False)

    if validation_results_df.empty or not trained_models:
        raise RuntimeError(
            "No requested models trained successfully. "
            f"See {output_dir / 'models_skipped.csv'} for details."
        )

    best_model_name = select_best_model(validation_results_df)
    best_model = trained_models[best_model_name]
    save_model(best_model, models_dir / "best_model.joblib")

    if args.save_predictions:
        for model_name in trained_models:
            save_prediction_file(
                split_frames["validation"],
                validation_predictions[model_name],
                model_name,
                predictions_dir / f"validation_predictions_{model_name}.csv",
            )
            save_prediction_file(
                split_frames["test"],
                test_predictions[model_name],
                model_name,
                predictions_dir / f"test_predictions_{model_name}.csv",
            )

    combined_results = build_combined_results(validation_results_df, test_results_df)
    best_summary = build_best_model_summary(
        best_model_name=best_model_name,
        validation_results=validation_results_df,
        test_results=test_results_df,
        feature_columns=common_features,
        split_summaries=split_summaries,
        seed=seed,
        input_dir=input_dir,
        output_dir=output_dir,
    )

    training_run_summary = {
        "run_timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "input_dir": str(input_dir),
        "output_dir": str(output_dir),
        "input_format": args.input_format,
        "seed": seed,
        "class_weight": args.class_weight,
        "models_requested": ",".join(requested_models),
        "models_trained": ",".join(trained_models.keys()),
        "models_skipped": ",".join(row["model_name"] for row in skipped_model_rows),
        "best_model_name": best_model_name,
        "feature_count": len(common_features),
        "feature_columns_used": ",".join(common_features),
        "max_train_contexts": args.max_train_contexts,
        "max_validation_contexts": args.max_validation_contexts,
        "max_test_contexts": args.max_test_contexts,
        "max_train_rows": args.max_train_rows,
        "save_predictions": bool(args.save_predictions),
        "train_rows": split_summaries["train"]["rows"],
        "validation_rows": split_summaries["validation"]["rows"],
        "test_rows": split_summaries["test"]["rows"],
        "train_decision_contexts": split_summaries["train"]["decision_contexts"],
        "validation_decision_contexts": split_summaries["validation"]["decision_contexts"],
        "test_decision_contexts": split_summaries["test"]["decision_contexts"],
    }

