def find_pairwise_file(input_dir: Path, split: str, input_format: str) -> Path:
    """Find one split file, preferring parquet when input_format is auto."""

    if split not in VALID_SPLITS:
        raise ValueError(f"Unsupported split: {split}")

    parquet_path = input_dir / f"{split}_pairwise_samples.parquet"
    csv_path = input_dir / f"{split}_pairwise_samples.csv"

    if input_format == "auto":
        if parquet_path.exists():
            return parquet_path
        if csv_path.exists():
            return csv_path
        raise FileNotFoundError(
            f"Missing {split} pairwise samples. Checked: {parquet_path}, {csv_path}"
        )

    if input_format == "parquet":
        if parquet_path.exists():
            return parquet_path
        raise FileNotFoundError(f"Missing requested parquet input: {parquet_path}")

    if input_format == "csv":
        if csv_path.exists():
            return csv_path
        raise FileNotFoundError(f"Missing requested CSV input: {csv_path}")

    raise ValueError(f"Unsupported input format: {input_format}")


def parquet_engine_available() -> bool:
    return find_spec("pyarrow") is not None or find_spec("fastparquet") is not None


def list_parquet_columns(path: Path) -> list[str]:
    if find_spec("pyarrow") is not None:
        import pyarrow.parquet as pq

        return list(pq.read_schema(path).names)

    if find_spec("fastparquet") is not None:
        import fastparquet

        return list(fastparquet.ParquetFile(path).columns)

    raise RuntimeError(
        "Parquet input requires pyarrow or fastparquet. "
        "Use --input-format csv or install a parquet engine."
    )


def list_input_columns(path: Path) -> list[str]:
    import pandas as pd

    suffix = path.suffix.lower()
    if suffix == ".parquet":
        return list_parquet_columns(path)
    if suffix == ".csv":
        return list(pd.read_csv(path, nrows=0).columns)
    raise ValueError(f"Unsupported input file extension: {path}")


def read_pairwise_split(
    input_dir: Path,
    split: str,
    input_format: str,
    columns: Sequence[str],
) -> Any:
    """Read one pairwise split using only requested columns that exist."""

    import pandas as pd

    path = find_pairwise_file(input_dir, split, input_format)
    suffix = path.suffix.lower()
    requested = list(dict.fromkeys(columns))
    available = list_input_columns(path)
    available_set = set(available)
    usecols = [column for column in requested if column in available_set]
    missing = [column for column in requested if column not in available_set]

    if missing:
        warnings.warn(f"{split}: missing requested columns: {missing}")
    if not usecols:
        raise ValueError(f"{split}: no requested columns are available in {path}")

    print(f"Reading {split}: {path}")
    print(f"{split}: reading {len(usecols)} of {len(available)} available columns")

    if suffix == ".parquet":
        if not parquet_engine_available():
            raise RuntimeError(
                "Parquet input requires pyarrow or fastparquet. "
                "Use --input-format csv or install a parquet engine."
            )
        return pd.read_parquet(path, columns=usecols)

    if suffix == ".csv":
        return pd.read_csv(path, usecols=usecols)

    raise ValueError(f"Unsupported input file extension: {path}")


def sample_decision_contexts(df: Any, max_contexts: int | None, seed: int) -> Any:
    """Sample complete route_id + position groups."""

    if max_contexts is None or max_contexts <= 0:
        return df

    missing = [column for column in CONTEXT_COLUMNS if column not in df.columns]
    if missing:
        raise ValueError(f"Cannot sample decision contexts; missing columns: {missing}")

    contexts = df.loc[:, CONTEXT_COLUMNS].drop_duplicates()
    if len(contexts) <= max_contexts:
        return df

    sampled_contexts = contexts.sample(n=max_contexts, random_state=seed)
    sampled = df.merge(sampled_contexts, on=CONTEXT_COLUMNS, how="inner")
    sampled = sampled.reset_index(drop=True)

    print(
        f"Sampled {len(sampled_contexts):,} complete decision contexts; "
        f"rows kept: {len(sampled):,} of {len(df):,}"
    )
    return sampled


def sample_rows(df: Any, max_rows: int | None, seed: int, split: str) -> Any:
    if max_rows is None or max_rows <= 0 or len(df) <= max_rows:
        return df

    warnings.warn(
        "Row sampling may break decision contexts and should not be used for top-k metrics."
    )
    sampled = df.sample(n=max_rows, random_state=seed).reset_index(drop=True)
    print(f"{split}: sampled {len(sampled):,} rows from {len(df):,} rows")
    return sampled


def label_counts(df: Any) -> dict[str, int]:
    labels = df[TARGET_COLUMN].value_counts(dropna=False).sort_index()
    return {str(label): int(count) for label, count in labels.items()}


def validate_pairwise_data(df: Any, split: str) -> dict[str, Any]:
    """Validate required columns and report decision-context quality."""

    missing_required = [
        column for column in [*CONTEXT_COLUMNS, TARGET_COLUMN] if column not in df.columns
    ]
    if missing_required:
        raise ValueError(f"{split}: missing required columns: {missing_required}")

    if df.empty:
        raise ValueError(f"{split}: input data is empty.")

    labels = df[TARGET_COLUMN]
    numeric_labels = labels.astype("int64")
    observed = set(numeric_labels.dropna().unique().tolist())
    if not observed.issubset({0, 1}):
        raise ValueError(f"{split}: labels must be 0/1. Observed: {sorted(observed)}")

    context_positive_counts = (
        numeric_labels.eq(1)
        .groupby([df["route_id"], df["position"]], dropna=False)
        .sum()
    )
    contexts = int(len(context_positive_counts))
    no_positive = int((context_positive_counts == 0).sum())
    multiple_positive = int((context_positive_counts > 1).sum())
    not_exactly_one = no_positive + multiple_positive

    if not_exactly_one:
        warnings.warn(
            f"{split}: {not_exactly_one:,} decision contexts do not have exactly "
            "one positive sample."
        )

    summary = {
        "split": split,
        "rows": int(len(df)),
        "decision_contexts": contexts,
        "positive_rows": int((numeric_labels == 1).sum()),
        "negative_rows": int((numeric_labels == 0).sum()),
        "contexts_no_positive": no_positive,
        "contexts_multiple_positive": multiple_positive,
        "contexts_not_exactly_one_positive": not_exactly_one,
    }

    print(
        f"{split}: rows={summary['rows']:,}, contexts={contexts:,}, "
        f"labels={label_counts(df)}"
    )
    return summary


def get_feature_columns(df: Any) -> list[str]:
    """Return default numeric features available in the dataframe."""

    available = []
    missing = []
    excluded_present = sorted(set(df.columns) & EXCLUDED_FEATURE_COLUMNS)

    for column in DEFAULT_FEATURE_COLUMNS:
        if column in df.columns and column not in EXCLUDED_FEATURE_COLUMNS:
            available.append(column)
        else:
            missing.append(column)

    if missing:
        warnings.warn(f"Missing default feature columns: {missing}")
    if "route_score" in excluded_present:
        print("Excluding route_score from features to avoid leakage.")

    if not available:
        raise ValueError("No usable feature columns remain.")

    return available


def prepare_xy(df: Any, feature_columns: Sequence[str]) -> tuple[Any, Any]:
    """Convert feature columns to numeric X and labels to integer y."""

    import pandas as pd

    missing = [column for column in feature_columns if column not in df.columns]
    if missing:
        raise ValueError(f"Missing feature columns during prepare_xy: {missing}")

    features = df.loc[:, list(feature_columns)].copy()
    for column in feature_columns:
        features[column] = pd.to_numeric(features[column], errors="coerce")
    features = features.astype("float32")

    labels = pd.to_numeric(df[TARGET_COLUMN], errors="coerce")
    if labels.isna().any():
        raise ValueError("Labels contain non-numeric values after conversion.")
    labels = labels.astype("int64")

    return features, labels


def train_model(
    model_name: str,
    X_train: Any,
    y_train: Any,
    seed: int,
    class_weight: str,
) -> Any:
    """Build and fit one requested model."""

    balanced = class_weight == "balanced"

    try:
        from sklearn.impute import SimpleImputer
        from sklearn.pipeline import Pipeline
    except ImportError as exc:
        raise ImportError("scikit-learn is required for model pipelines.") from exc

    if model_name == "logistic_regression":
        from sklearn.linear_model import LogisticRegression
        from sklearn.preprocessing import StandardScaler

        estimator = LogisticRegression(
            max_iter=1000,
            solver="lbfgs",
            class_weight="balanced" if balanced else None,
            random_state=seed,
        )
        model = Pipeline(
            steps=[
                ("imputer", SimpleImputer(strategy="median")),
                ("scaler", StandardScaler()),
                ("model", estimator),
            ]
        )
    elif model_name == "random_forest":
        from sklearn.ensemble import RandomForestClassifier

        estimator = RandomForestClassifier(
            n_estimators=200,
            max_depth=None,
            min_samples_leaf=2,
            n_jobs=-1,
            class_weight="balanced_subsample" if balanced else None,
            random_state=seed,
        )
        model = Pipeline(
            steps=[
                ("imputer", SimpleImputer(strategy="median")),
                ("model", estimator),
            ]
        )
    elif model_name == "xgboost":
        if find_spec("xgboost") is None:
            raise ImportError("xgboost is not installed.")
        from xgboost import XGBClassifier

        estimator = XGBClassifier(
            objective="binary:logistic",
            eval_metric="logloss",
            n_estimators=500,
            max_depth=6,
            learning_rate=0.05,
            subsample=0.8,
            colsample_bytree=0.8,
            n_jobs=-1,
            random_state=seed,
        )
        model = Pipeline(
            steps=[
                ("imputer", SimpleImputer(strategy="median")),
                ("model", estimator),
            ]
        )
    elif model_name == "lightgbm":
        if find_spec("lightgbm") is None:
            raise ImportError("lightgbm is not installed.")
        from lightgbm import LGBMClassifier

        estimator = LGBMClassifier(
            n_estimators=500,
            learning_rate=0.05,
            num_leaves=63,
            subsample=0.8,
            colsample_bytree=0.8,
            class_weight="balanced" if balanced else None,
            random_state=seed,
            n_jobs=-1,
            verbose=-1,
        )
        model = Pipeline(
            steps=[
                ("imputer", SimpleImputer(strategy="median")),
                ("model", estimator),
            ]
        )
    elif model_name == "catboost":
        if find_spec("catboost") is None:
            raise ImportError("catboost is not installed.")
        from catboost import CatBoostClassifier

        kwargs = {
            "iterations": 600,
            "depth": 8,
            "learning_rate": 0.05,
            "loss_function": "Logloss",
            "eval_metric": "AUC",
            "random_seed": seed,
            "verbose": False,
            "allow_writing_files": False,
        }
        if balanced:
            kwargs["auto_class_weights"] = "Balanced"
        estimator = CatBoostClassifier(**kwargs)
        model = Pipeline(
            steps=[
                ("imputer", SimpleImputer(strategy="median")),
                ("model", estimator),
            ]
        )
    else:
        raise ValueError(f"Unsupported model: {model_name}")

    model.fit(X_train, y_train)
    return model


def predict_proba_safely(model: Any, X: Any) -> Any:
    """Return a clipped probability for the positive class."""

    import numpy as np

    if hasattr(model, "predict_proba"):
        probabilities = np.asarray(model.predict_proba(X), dtype=float)
        if probabilities.ndim == 2:
            classes = getattr(model, "classes_", None)
            if classes is not None and 1 in list(classes):
                positive_index = list(classes).index(1)
            else:
                positive_index = min(1, probabilities.shape[1] - 1)
            y_prob = probabilities[:, positive_index]
        else:
            y_prob = probabilities.reshape(-1)
    elif hasattr(model, "decision_function"):
        scores = np.asarray(model.decision_function(X), dtype=float).reshape(-1)
        scores = np.clip(scores, -700, 700)
        y_prob = 1.0 / (1.0 + np.exp(-scores))
    else:
        y_prob = np.asarray(model.predict(X), dtype=float).reshape(-1)

    return np.clip(y_prob, 1e-15, 1.0 - 1e-15)


def compute_binary_metrics(y_true: Any, y_prob: Any) -> dict[str, float]:
    """Compute binary metrics safely."""

    import numpy as np
    from sklearn.metrics import (
        accuracy_score,
        average_precision_score,
        f1_score,
        log_loss,
        precision_score,
        recall_score,
        roc_auc_score,
    )

    y_true = np.asarray(y_true, dtype=int)
    y_prob = np.asarray(y_prob, dtype=float)
    y_pred = (y_prob >= 0.5).astype(int)

    def safe(name: str, func: Any) -> float:
        try:
            return float(func())
        except Exception as exc:
            warnings.warn(f"Could not compute {name}: {exc}")
            return float("nan")

    return {
        "accuracy": safe("accuracy", lambda: accuracy_score(y_true, y_pred)),
        "precision": safe(
            "precision", lambda: precision_score(y_true, y_pred, zero_division=0)
        ),
        "recall": safe("recall", lambda: recall_score(y_true, y_pred, zero_division=0)),
        "f1": safe("f1", lambda: f1_score(y_true, y_pred, zero_division=0)),
        "roc_auc": safe("roc_auc", lambda: roc_auc_score(y_true, y_prob)),
        "average_precision": safe(
            "average_precision", lambda: average_precision_score(y_true, y_prob)
        ),
        "log_loss": safe("log_loss", lambda: log_loss(y_true, y_prob, labels=[0, 1])),
    }


def compute_sampled_topk_metrics(df: Any, y_prob: Any) -> dict[str, Any]:
    """Compute sampled top-k accuracy by route_id + position context."""

    import numpy as np

    missing = [column for column in [*CONTEXT_COLUMNS, TARGET_COLUMN] if column not in df.columns]
    if missing:
        warnings.warn(f"Cannot compute top-k metrics; missing columns: {missing}")
        return {
            "sampled_top1_accuracy": float("nan"),
            "sampled_top3_accuracy": float("nan"),
            "sampled_top5_accuracy": float("nan"),
            "evaluated_contexts": 0,
            "skipped_contexts_no_positive": 0,
            "contexts_multiple_positive": 0,
        }

    temp = df.loc[:, [*CONTEXT_COLUMNS, TARGET_COLUMN]].copy()
    temp[TARGET_COLUMN] = temp[TARGET_COLUMN].astype("int64")
    temp["predicted_probability"] = np.asarray(y_prob, dtype=float)

    positive_counts = temp.groupby(CONTEXT_COLUMNS, dropna=False)[TARGET_COLUMN].sum()
    skipped_no_positive = int((positive_counts == 0).sum())
    multiple_positive = int((positive_counts > 1).sum())

    ranked = temp.sort_values(
        by=[*CONTEXT_COLUMNS, "predicted_probability"],
        ascending=[True, True, False],
        kind="mergesort",
    )
    ranked["_rank"] = ranked.groupby(CONTEXT_COLUMNS, dropna=False).cumcount() + 1

    positive_ranks = (
        ranked.loc[ranked[TARGET_COLUMN] == 1]
        .groupby(CONTEXT_COLUMNS, dropna=False)["_rank"]
        .min()
    )
    evaluated_contexts = int(len(positive_ranks))

    if evaluated_contexts == 0:
        return {
            "sampled_top1_accuracy": float("nan"),
            "sampled_top3_accuracy": float("nan"),
            "sampled_top5_accuracy": float("nan"),
            "evaluated_contexts": 0,
            "skipped_contexts_no_positive": skipped_no_positive,
            "contexts_multiple_positive": multiple_positive,
        }

    return {
        "sampled_top1_accuracy": float((positive_ranks <= 1).mean()),
        "sampled_top3_accuracy": float((positive_ranks <= 3).mean()),
        "sampled_top5_accuracy": float((positive_ranks <= 5).mean()),
        "evaluated_contexts": evaluated_contexts,
        "skipped_contexts_no_positive": skipped_no_positive,
        "contexts_multiple_positive": multiple_positive,
    }


def evaluate_split(model_name: str, model: Any, df: Any, X: Any, y: Any) -> tuple[dict[str, Any], Any]:
    y_prob = predict_proba_safely(model, X)
    metrics = {"model_name": model_name}
    metrics.update(compute_binary_metrics(y, y_prob))
    metrics.update(compute_sampled_topk_metrics(df, y_prob))
    return metrics, y_prob


def final_estimator(model: Any) -> Any:
    if hasattr(model, "named_steps") and "model" in model.named_steps:
        return model.named_steps["model"]
    return model


def extract_feature_importance(
    model: Any,
    model_name: str,
    feature_columns: Sequence[str],
) -> list[dict[str, Any]]:
    """Extract feature importance rows for models that expose it."""

    import numpy as np

    estimator = final_estimator(model)
    importances = None
    signed = None
    importance_type = ""

    try:
        if model_name == "logistic_regression" and hasattr(estimator, "coef_"):
            signed = np.asarray(estimator.coef_, dtype=float).reshape(-1)
            importances = np.abs(signed)
            importance_type = "abs_logistic_coefficient"
        elif hasattr(estimator, "feature_importances_"):
            importances = np.asarray(estimator.feature_importances_, dtype=float).reshape(-1)
            signed = importances
            importance_type = "feature_importances_"
        elif hasattr(estimator, "get_feature_importance"):
            importances = np.asarray(estimator.get_feature_importance(), dtype=float).reshape(-1)
            signed = importances
            importance_type = "feature_importances_"
    except Exception as exc:
        warnings.warn(f"{model_name}: could not extract feature importance: {exc}")
        return []

    if importances is None or len(importances) != len(feature_columns):
        warnings.warn(f"{model_name}: feature importance is unavailable.")
        return []

    rows = []
    for index, feature in enumerate(feature_columns):
        rows.append(
            {
                "model_name": model_name,
                "feature": feature,
                "importance": float(importances[index]),
                "signed_importance": float(signed[index]) if signed is not None else float(importances[index]),
                "importance_type": importance_type,
            }
        )
    return rows


def metric_desc_sort_value(value: Any) -> float:
    try:
        numeric = float(value)
    except (TypeError, ValueError):
        return -math.inf
    return -math.inf if math.isnan(numeric) else numeric


def metric_asc_sort_value(value: Any) -> float:
    try:
        numeric = float(value)
    except (TypeError, ValueError):
        return math.inf
    return math.inf if math.isnan(numeric) else numeric


def select_best_model(validation_results: Any) -> str:
    if validation_results.empty:
        raise ValueError("No validation results available for model selection.")

    sortable = validation_results.copy()
    sortable["_top1"] = sortable["sampled_top1_accuracy"].apply(metric_desc_sort_value)
    sortable["_roc_auc"] = sortable["roc_auc"].apply(metric_desc_sort_value)
    sortable["_average_precision"] = sortable["average_precision"].apply(metric_desc_sort_value)
    sortable["_log_loss"] = sortable["log_loss"].apply(metric_asc_sort_value)

    sortable = sortable.sort_values(
        by=["_top1", "_roc_auc", "_average_precision", "_log_loss"],
        ascending=[False, False, False, True],
        kind="mergesort",
    )
    return str(sortable.iloc[0]["model_name"])


def prefix_metrics(df: Any, prefix: str) -> Any:
    renamed = df.copy()
    renamed = renamed.rename(
        columns={column: f"{prefix}_{column}" for column in renamed.columns if column != "model_name"}
    )
    return renamed


def build_combined_results(validation_results: Any, test_results: Any) -> Any:
    combined = prefix_metrics(validation_results, "validation").merge(
        prefix_metrics(test_results, "test"),
        on="model_name",
        how="outer",
    )
    return combined


def json_clean(value: Any) -> Any:
    import numpy as np

    if isinstance(value, dict):
        return {str(key): json_clean(item) for key, item in value.items()}
    if isinstance(value, list):
        return [json_clean(item) for item in value]
    if isinstance(value, tuple):
        return [json_clean(item) for item in value]
    if isinstance(value, (np.integer,)):
        return int(value)
    if isinstance(value, (np.floating,)):
        value = float(value)
    if isinstance(value, float) and math.isnan(value):
        return None
    return value


